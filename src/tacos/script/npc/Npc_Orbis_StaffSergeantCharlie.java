    private final int required_quantity = 100;
    private final int reward_exp = 500;
    private int selected = -1;
    private boolean asked = false;

    @Override
    public boolean action(int status, int answer) {
        switch (status) {
            case 0 -> {
                if (this.asked) {
                    // 取引の確認で No
                    say("そうか… あまり悪い条件とは思わないがな。タイミングが合えば掘り出し物と交換できるかもな。とにかく気が向いたらいつでも来いよ。");
                    return false;
                }
                NpcScriptTag nt = new NpcScriptTag();
                nt.add("おい ちょっといいか？実は自分はこの付近から得られる色々なものを別の村で売っている仕事をしているのだ。最近はモンスターが手に負えないから商品の仕入れに困っている。どうだ？自分と取引しないか？");
                say(nt, false, true);
                return true;
            }
            case 1 -> {
                this.asked = true;
                NpcScriptTag nt = new NpcScriptTag();
                nt.add("取引というのは簡単だ。自分が必要なものを持ってくれればその代わりに自分が持っているものを君にやろう。しかしだ、大勢の人を相手にすると持っているのものが何時も同じとは限らない。交換する度に君にあげられるものが違うかも知れないぜ。どうだ？やってみるか？");
                askYesNo(nt);
                return true;
            }
            case 2 -> {
                if (0 <= this.selected) {
                    // 交換の確認で No
                    say("そうか… あまり悪い条件とは思わないがな。タイミングが合えば掘り出し物と交換できるかもな。とにかく気が向いたらいつでも来いよ。");
                    return false;
                }
                NpcScriptTag nt = new NpcScriptTag();
                nt.add("よし！まず自分にどんなものをくれるか選んでくれ。いいものをくれるともっといいものと交換できるからな。");
                for (int i = 0; i < this.item_ids.length; i++) {
                    nt.add(" #L" + i + "##v" + this.item_ids[i] + "#  #t" + this.item_ids[i] + "##l");
                }
                askMenu(nt);
                return true;
            }
            case 3 -> {
                if (answer < 0 || this.item_ids.length <= answer) {
                    return false;
                }
                this.selected = answer;
                NpcScriptTag nt = new NpcScriptTag();
                nt.add("#b#t" + this.item_ids[this.selected] + "##k " + this.required_quantity + "個を俺のものと交換したいということか？まず交換する前に消費とETCのインベントリが空いているか確認してくれ。では本当に交換するか？");
                askYesNo(nt);
                return true;
            }
            case 4 -> {
                int item_id = this.item_ids[this.selected];
                int[] prize = this.prizes[this.selected][Randomizer.nextInt(this.prizes[this.selected].length)];
                if (!haveItem(item_id, this.required_quantity)) {
                    say("うむ… 君 #b#t" + item_id + "##k " + this.required_quantity + "個はちゃんと持っているのか？ならインベントリが空いているかもう一度確認してくれ。");
                    return false;
                }
                if (!canHold(prize[0], prize[1])) {
                    // 翻訳
                    say("ETCインベントリがいっぱいのようだな。俺と交換するには空きが必要だ！空きを作ってから会いに来な…");
                    return false;
                }
                removeItem(item_id, this.required_quantity);
                gainExp(this.reward_exp);
                gainItem(prize[0], prize[1]); // TODO : item effect.
                // 翻訳
                say("お前の#b#t" + item_id + "# " + this.required_quantity + "個#kと引き換えに、俺の#b" + prize[1] + " #t" + prize[0] + "#個#kをやろう。どうだ？交換で渡したアイテムは気に入ったか？俺はしばらくここにいるから、もっとアイテムを集めたら、いつでも取引に応じるぞ…");
                return false;
            }
            default -> {
            }
        }
        return false;
    }
