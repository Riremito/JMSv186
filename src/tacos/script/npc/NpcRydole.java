    private int phase = PHASE_START;
    private int last_status = 0;
    private int node = 0;
    private int said = 0;
    private int recipe = 0;
    private int number = 0;
    private String text_no = "";

    @Override
    public boolean action(int status, int answer) {
        if (status < this.last_status) {
            // askYesNo でいいえを選択した
            if (!this.text_no.isEmpty()) {
                say(this.text_no);
            }
            return false;
        }
        this.last_status = status;
        if (this.phase == PHASE_START) {
            this.phase = PHASE_MENU;
            this.text_no = this.text_intro_no;
            askYesNo(this.text_intro);
            return true;
        }
        if (this.phase == PHASE_MENU_ANSWER) {
            if (answer < 0 || this.menu_children[this.node].length <= answer || this.menu_children[this.node][answer] < 0) {
                return false;
            }
            int child = this.menu_children[this.node][answer];
            if (child < RECIPE) {
                this.node = child;
                this.said = 0;
                this.phase = PHASE_MENU;
            } else {
                this.recipe = child - RECIPE;
                this.phase = PHASE_RECIPE;
            }
        }
        if (this.phase == PHASE_MENU) {
            if (this.said < this.menu_says[this.node].length) {
                // メニューがない場合は会話のみ
                if (this.menu_texts[this.node].isEmpty() && this.said == this.menu_says[this.node].length - 1) {
                    say(this.menu_says[this.node][this.said]);
                    return false;
                }
                say(this.menu_says[this.node][this.said++], false, true);
                return true;
            }
            if (this.menu_texts[this.node].isEmpty()) {
                return false;
            }
            NpcScriptTag nt = new NpcScriptTag();
            nt.add(this.menu_texts[this.node], false);
            askMenu(nt);
            this.phase = PHASE_MENU_ANSWER;
            return true;
        }
        if (this.phase == PHASE_NUMBER_ANSWER) {
            this.number = answer;
        }
        int type = this.recipes[this.recipe][0];
        int index = this.recipes[this.recipe][1];
        String[] texts = this.recipe_texts[this.recipe];
        int[] values = this.recipe_values[this.recipe];
        boolean is_number = false;
        int number_default = 0;
        int number_min = 0;
        int number_max = 0;
        boolean is_random = false;
        int random_max = 0;
        String text_ask = "";
        String text_confirm = "";
        String text_answer_no = "";
        String text_fail = "";
        String text_ok = "";
        String text_failure_fail = "";
        String text_failure_ok = "";
        switch (type) {
            case TYPE_CHAT_MESSAGE3 -> {
                String make_item = texts[0];
                String need_item = texts[1];
                int req_level = values[0];
                String item_option = texts[2];
                is_random = true;
                random_max = 10;
                text_confirm = "" + make_item + "を活性剤を使って作るには、以下のアイテムが必要よ。制限レベルは" + req_level + "、基本攻撃力は" + item_option + "。活性剤を使うと、アイテムのオプションが全体的に上がることもあるが、#b前より悪くなることもあるし、10%の確率で失敗することもあるから、気をつけてくれ#k。どうだい？作るかい？\r\n\r\n#b" + need_item;
                text_answer_no = "わかった。活性剤を使うと、アイテムを作るのに失敗して、アイテムを無駄にしてしまう危険もあるからな。俺だって慎重になるさ。でも、気が変わったら気軽に来てくれ。";
                text_fail = "必要なアイテムがすべてそろっているか確認してくれ。そろっているなら、装備インベントリがいっぱいでないか確認してくれ。";
                text_ok = "はい、どうぞ。" + make_item + "だ！すべてうまくいったぞ。普通の武器よりずっと強力だ。また会えるのを楽しみにしているよ！";
                text_failure_fail = "必要なアイテムがすべてそろっているか確認してくれ。そろっているなら、装備インベントリがいっぱいでないか確認してくれ。";
                text_failure_ok = "ああ、しまった…活性剤を入れすぎたみたいだ…アイテムが全部なくなっちまった…すまない。こうなる可能性があることは伝えておいたから、わかってもらえるといいんだが。";
            }
            case TYPE_CHAT_MESSAGE4 -> {
                String make_item = texts[0];
                String need_item = texts[1];
                int req_level = values[0];
                String item_option = texts[2];
                text_confirm = "" + make_item + "を強化するには、以下の材料が必要よ。制限レベルは" + req_level + "、アイテムの基本オプションは" + item_option + "だから、本当に必要か確かめてくれ。で、作ってほしいか？\r\n\r\n#b" + need_item;
                text_answer_no = "材料がないのか？いいさ。俺はここで待っているから、材料を集め続けて、また話しかけてくれ。";
                text_fail = "必要なアイテムがすべてそろっているか確認してくれ。そろっているなら、装備インベントリがいっぱいでないか確認してくれ。";
                text_ok = "ほら、" + make_item + "だ！できたてだから、丁寧に扱ってくれよ。また会えるのを楽しみにしているよ！";
            }
            default -> {
                return false;
            }
        }
        if (this.phase == PHASE_RECIPE && is_number) {
            this.phase = PHASE_NUMBER_ANSWER;
            askNumber(text_ask, number_default, number_min, number_max);
            return true;
        }
        if (this.phase == PHASE_RECIPE || this.phase == PHASE_NUMBER_ANSWER) {
            this.phase = PHASE_EXECUTE;
            this.text_no = text_answer_no;
            askYesNo(text_confirm);
            return true;
        }
        if (this.phase != PHASE_EXECUTE) {
            return false;
        }
        // lua : random(1, random_max) == 1 で製作に失敗
        boolean failure = is_random && Randomizer.rand(1, random_max) == 1;
        int[] base = failure ? this.recipe_exchanges_failure[this.recipe] : this.recipe_exchanges[this.recipe];
        int count = is_number ? this.number : 1;
        int[] items = new int[base.length - 1];
        for (int i = 0; i < items.length; i++) {
            items[i] = (i % 2 == 0) ? base[i + 1] : base[i + 1] * count;
        }
        // TODO : 活性剤を使った製作はアイテムの能力値が変動する (exchangeEx の Variation)
        if (!exchange(base[0] * count, items)) {
            say(failure ? text_failure_fail : text_fail);
            return false;
        }
        say(failure ? text_failure_ok : text_ok);
        return false;
    }
