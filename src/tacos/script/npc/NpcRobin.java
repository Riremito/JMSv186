    private int selected = -1;

    @Override
    public boolean action(int status, int answer) {
        if (status == 0) {
            // 翻訳
            NpcScriptTag nt = new NpcScriptTag();
            nt.add("さあ…旅について知りたいことは何でも聞いてね！！");
            for (int i = 0; i < this.questions.length; i++) {
                nt.addMenu(i, this.questions[i]);
            }
            askMenu(nt);
            return true;
        }
        if (status == 1) {
            if (answer < 0 || this.answers.length <= answer) {
                return false;
            }
            this.selected = answer;
        }
        int index = status - 1;
        if (this.selected < 0 || index < 0 || this.answers[this.selected].length <= index) {
            return false;
        }
        boolean next = index + 1 < this.answers[this.selected].length;
        say(this.answers[this.selected][index], false, next);
        return next;
    }
