    @Override
    public boolean questStart(int status, int answer) {
        // 翻訳
        String text_level_victoria = "どのレベル帯のモンスターを見る？\r\n#b#L0# レベル 1 ～ 10#l\r\n#L1# レベル 11 ～ 20#l\r\n#L2# レベル 21 ～ 30#l\r\n#L3# レベル 31 ～ 40#l\r\n#L4# レベル 41 ～ 50#l\r\n#L5# レベル 51 ～ 60#l\r\n#L6# レベル 61 ～ 70#l\r\n#L7# 終了#l";
        // 翻訳
        String text_level_ossyria = "どのレベル帯のモンスターを見る？\r\n#b#L0# レベル 21 ～ 30#l\r\n#L1# レベル 31 ～ 35#l\r\n#L2# レベル 36 ～ 40#l\r\n#L3# レベル 41 ～ 45#l\r\n#L4# レベル 46 ～ 50#l\r\n#L5# レベル 51 ～ 60#l\r\n#L6# レベル 61 ～ 70#l\r\n#L7# レベル 71 ～ 80#l\r\n#L8# レベル 81 ～ 90#l\r\n#L9# レベル 91 ～ 100#l\r\n#L10# レベル 101 以上#l\r\n#L11# 終了#l";

        if (this.step == this.step_start) {
            // lua の selectedMob2 - selectedMob4, 以前のクエストが進行中の場合は選択できない
            int index = getQuestId() - this.quest_daily_first;
            for (int i = 0; i < index; i++) {
                if (getQuestStatus(this.qcode_daily_first + i) == 1) {
                    // 翻訳
                    say("うーん、以前の指定モンスター狩りイベントを進行中なんじゃない？一度に指定できるモンスターは1種類だけだから、現在進行中のクエストを放棄してね。");
                    return false;
                }
            }
            this.step = this.step_intro;
            // 翻訳
            say("何か面白いことないかなあ？ね？君も何か面白いことないかな…と思って私を訪ねてきたんでしょ？だったら久しぶりに私の魔法の腕前を披露しようかな？どんな魔法かって？", false, true);
            return true;
        }

        if (this.step == this.step_intro) {
            int map_id = getMapId();
            if (map_id == this.map_maple_road || map_id == this.map_southperry) {
                this.region = this.region_island;
            }
            for (int id : this.maps_victoria) {
                if (map_id == id) {
                    this.region = this.region_victoria;
                }
            }
            for (int id : this.maps_ossyria) {
                if (map_id == id) {
                    this.region = this.region_ossyria;
                }
            }
            for (int i = 0; i < this.maps_overseas.length; i++) {
                if (map_id == this.maps_overseas[i]) {
                    this.region = this.region_overseas;
                    this.block = i;
                }
            }
            this.step = this.step_region;
            // 翻訳
            say("それはね、君がよく狩るモンスターを1種類選ぶと、今日一日だけボーナス経験値がもらえるようになる魔法なの。素敵でしょ？さあ、どのモンスターにするか考えて、リストから選んでね。", false, this.region != -1);
            // 対象外のマップでは何もしない
            return this.region != -1;
        }

        boolean selected = (this.step == this.step_list);
        if (this.step == this.step_region) {
            if (this.region == this.region_victoria || this.region == this.region_ossyria) {
                this.step = this.step_top;
                // 翻訳
                askMenu("まずは君が狩るのにちょうどいいモンスターをおすすめしてあげる。ほしいモンスターがいなければ、全体表示を選んでモンスターを選べばいいよ。\r\n#b#L0# おすすめリストを見る\r\n#L1# 全体リストを見る#l\r\n#L2# やめる#l");
                return true;
            }
            // メイプルアイランド, 海外
            this.list = this.list_other;
            if (this.region == this.region_island) {
                this.block = 0;
            }
            this.page = 0;
        } else if (this.step == this.step_top) {
            if (answer == 0) {
                // おすすめリスト
                int[][] levels = (this.region == this.region_victoria) ? this.victoria_recommend_levels : this.ossyria_recommend_levels;
                int level = getLevel();
                this.block = -1;
                for (int i = 0; i < levels.length; i++) {
                    if (levels[i][0] <= level && level <= levels[i][1]) {
                        this.block = i;
                    }
                }
                if (this.block == -1) {
                    // 翻訳
                    say("オシリアにはレベル20以下のユーザー向けのおすすめリストはないの。ビクトリアで話しかけてみたらどう？");
                    return false;
                }
                this.list = this.list_recommend;
                this.page = 0;
            } else if (answer == 1) {
                // 全体リスト
                this.step = this.step_level;
                askMenu((this.region == this.region_victoria) ? text_level_victoria : text_level_ossyria);
                return true;
            } else {
                // 翻訳
                say("私が新しく覚えた魔法なんて大したことないと思ってるの？気が変わったら、また話しかけてね。");
                return false;
            }
        } else if (this.step == this.step_level) {
            int bands = (this.region == this.region_victoria) ? this.victoria_texts.length : this.ossyria_texts.length;
            if (answer < 0 || bands <= answer) {
                // 終了
                return false;
            }
            this.list = this.list_full;
            this.block = answer;
            this.page = 0;
        } else if (this.step != this.step_list) {
            return false;
        }

        // 地域とリストの種類に対応するメニュー
        String[][] texts = this.maple_island_texts;
        int[][][] entries = this.maple_island_entries;
        boolean[] loop = this.maple_island_loop;
        if (this.region == this.region_overseas) {
            texts = this.overseas_texts;
            entries = this.overseas_entries;
            loop = this.overseas_loop;
        } else if (this.region == this.region_victoria && this.list == this.list_full) {
            texts = this.victoria_texts;
            entries = this.victoria_entries;
            loop = this.victoria_loop;
        } else if (this.region == this.region_victoria) {
            texts = this.victoria_recommend_texts;
            entries = this.victoria_recommend_entries;
            loop = this.victoria_recommend_loop;
        } else if (this.region == this.region_ossyria && this.list == this.list_full) {
            texts = this.ossyria_texts;
            entries = this.ossyria_entries;
            loop = this.ossyria_loop;
        } else if (this.region == this.region_ossyria) {
            texts = this.ossyria_recommend_texts;
            entries = this.ossyria_recommend_entries;
            loop = this.ossyria_recommend_loop;
        }

        if (selected) {
            int[] page_entries = entries[this.block][this.page];
            int kind = -1;
            int value = 0;
            int exp = 0;
            for (int i = 0; i < page_entries.length; i += 4) {
                if (page_entries[i] == answer) {
                    kind = page_entries[i + 1];
                    value = page_entries[i + 2];
                    exp = page_entries[i + 3];
                }
            }
            if (kind == 0) {
                // 全体リストの経験値はレベル帯で決まる
                if (this.list == this.list_full) {
                    exp = (this.region == this.region_victoria) ? this.victoria_exp[this.block] : this.ossyria_exp[this.block];
                    if (this.region == this.region_victoria && this.block == this.victoria_exp.length - 1) {
                        for (int id : this.victoria_exp_exception) {
                            if (value == id) {
                                exp = this.victoria_exp_exception_value;
                            }
                        }
                    }
                }
                int qcode = (getQuestId() == this.quest_selected_mob) ? this.qcode_selected_mob : (this.qcode_daily_first + getQuestId() - this.quest_daily_first);
                // TODO : lua の qr.selectedMob( qcode, code, 0, exp ) (選んだモンスターを狩ると追加の経験値がもらえる) は未実装
                getPlayer().DebugMsg("selectedMob : qcode = " + qcode + ", mob = " + value + ", exp = " + exp);
                // 翻訳
                say("君が選んだ狩りのモンスターは#b#o" + value + "##kで合ってる？これからクエストが進行中の間、選んだモンスターを狩ると追加の経験値がもらえるよ。別のモンスターを選びたい場合は、クエストを放棄してから選び直してね。");
                return false;
            }
            if (kind == 1) {
                // 次のページ
                this.page = value;
            } else if (kind == 2 || (this.list == this.list_full && !loop[this.block])) {
                // 全体リストのレベル選択に戻る
                this.step = this.step_level;
                askMenu((this.region == this.region_victoria) ? text_level_victoria : text_level_ossyria);
                return true;
            } else if (loop[this.block]) {
                // 前のページ, 最初のページ
                this.page = 0;
            } else if (this.list == this.list_other) {
                // 翻訳
                say("エラーが発生したよ。しばらくしてからもう一度試してね。");
                return false;
            } else {
                return false;
            }
        }

        // モンスターの選択
        this.step = this.step_list;
        askMenu(texts[this.block][this.page]);
        return true;
    }
